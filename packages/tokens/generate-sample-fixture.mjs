#!/usr/bin/env node
// Regenerates figma-export.sample.json from the real primitives/semantic/
// density/breakpoint.json files, then re-plants the same 3 intentional
// drift cases sync figma's demo depends on. Run this any time those four
// files change so the sample can't go stale (see CLAUDE.md's sync figma
// section) — wired into .githooks/pre-commit so it happens automatically.
import { readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";

const __dirname = path.dirname(fileURLToPath(import.meta.url));

function load(file) {
  return JSON.parse(readFileSync(path.join(__dirname, file), "utf-8"));
}

const primitives = load("primitives.json");
const semantic = load("semantic.json");
const density = load("density.json");
const breakpoint = load("breakpoint.json");

// --- Plant exactly 3 drift cases, same as sync figma's documented demo ---

// 1. missingInCode: a new primitive Figma has that code hasn't picked up yet.
primitives.color.blue["550"] = "#3a70f0";

// 2. valueMismatch: Dark-mode-only edit (Light still matches code).
semantic.color.action.primary.default.value.dark = "{color.blue.400}";

// 3. missingInFigma: a token code has that this export doesn't include.
delete density.spacing["160"];

const output = {
  _comment:
    "Sample output shape from an F8igma Console variable export, mirroring the primitives/semantic/density/breakpoint schema. Has exactly 3 intentional drift cases for exercising sync figma: color.blue.550 is missingInCode (new primitive not yet in code), color.action.primary.default is a Dark-mode-only valueMismatch (Light still matches), density.spacing.160 is missingInFigma (present in code, absent from this export). Generated by `node packages/tokens/generate-sample-fixture.mjs` — do not hand-edit, regenerate instead. Run latent sync figma --file <real export>.json against your actual export.",
  primitives,
  semantic,
  density,
  breakpoint,
};

const outPath = path.join(__dirname, "figma-export.sample.json");
writeFileSync(outPath, JSON.stringify(output, null, 2) + "\n");
console.log(`Regenerated ${path.relative(process.cwd(), outPath)}`);
