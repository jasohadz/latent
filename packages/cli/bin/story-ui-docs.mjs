// Generates what Story UI reads to learn Latent (packages/storybook/
// story-ui-docs/ + story-ui-considerations.md) from the same sources every
// other surface uses: each component's .doc.mjs and the token JSON. Never
// hand-edit the output — `latent story-ui-docs --write` regenerates it, and
// the pre-commit hook does so whenever a .doc.mjs or token file is staged.
//
// Shaped around how Story UI actually consumes docs (read from its source,
// @tpitre/story-ui 5.21 — story-generator/documentationLoader.js and
// considerationsLoader.js), not its README alone:
// - Each docs file is cut at 8,000 chars and all of them together at
//   24,000 — so the catalog is split across files and the whole set is
//   checked against both budgets here, failing loudly instead of letting
//   Story UI silently truncate the tail.
// - README* files are skipped as instructions, so the human-facing README
//   here can say "generated, don't edit" without costing prompt budget.
// - Props are left out on purpose: Story UI already reads every prop from
//   the .tsx source into its own catalog. These docs carry what TypeScript
//   can't — when to use a component, its doNot rules, a real example — and
//   the token names, since Story UI writes a CSS module per story.
// - The considerations file is parsed by markers (**Import Path**,
//   "## Core Principles", "### ✅ DO"/"### ❌ DON'T", numbered
//   **Wrong**/**Right**/**Why** error patterns), so it's emitted in exactly
//   that shape.
import { readFileSync } from "node:fs";
import path from "node:path";

export const PER_FILE_BUDGET = 8000;
export const TOTAL_BUDGET = 24000;
// Headroom for the "## Component Documentation from <path>" header Story UI
// prepends to every file before measuring the total.
const FILE_HEADER_ALLOWANCE = 80;

const firstSentence = (s) => String(s).trim().split(/(?<=[.!?])\s/)[0];
const oneLine = (s) => String(s).replace(/\s+/g, " ").trim();

export function readStoryUiImportPath(configPath) {
  const m = /"importPath"\s*:\s*"([^"]+)"/.exec(readFileSync(configPath, "utf-8"));
  if (!m) throw new Error(`no importPath in ${configPath}`);
  return m[1];
}

function componentEntry(doc) {
  const lines = [`### ${doc.name}`, firstSentence(doc.summary), `Example: \`${oneLine(doc.example)}\``];
  for (const rule of doc.doNot) lines.push(`- ${firstSentence(rule)}`);
  return lines.join("\n");
}

// Groups token names by their parent path so 300 tokens read as ~40 lines:
//   --lat-color-text-{primary,secondary,tertiary,...}
function tokenLines(names) {
  const groups = new Map();
  for (const n of names) {
    const parts = n.split(".");
    const leaf = parts.pop();
    const parent = parts.join("-");
    if (!groups.has(parent)) groups.set(parent, []);
    groups.get(parent).push(leaf);
  }
  return [...groups].map(([parent, leaves]) =>
    leaves.length === 1 ? `- \`--lat-${parent}-${leaves[0]}\`` : `- \`--lat-${parent}-{${leaves.join(",")}}\``,
  );
}

export function buildStoryUiDocs({ docs, semanticNames, densityNames, codeOnlyNames, elevationNames, importPath }) {
  const files = {};

  // --- catalog, split so no file crosses the per-file budget ---
  const entries = docs.map(componentEntry);
  const chunks = [[]];
  const intro = "Every Latent component, what it's for, and the rules for using it. Props come from the TypeScript source.";
  let size = intro.length;
  for (const e of entries) {
    if (size + e.length + 2 > PER_FILE_BUDGET - FILE_HEADER_ALLOWANCE && chunks.at(-1).length) {
      chunks.push([]);
      size = intro.length;
    }
    chunks.at(-1).push(e);
    size += e.length + 2;
  }
  chunks.forEach((chunk, i) => {
    const first = chunk[0].split("\n")[0].slice(4);
    const last = chunk.at(-1).split("\n")[0].slice(4);
    files[`components/catalog-${i + 1}.md`] = `${intro} (${first}–${last})\n\n${chunk.join("\n\n")}\n`;
  });

  // --- token names (values deliberately omitted: stories must reference the
  // variable so they follow the theme, light/dark mode, and density) ---
  const semanticOnly = semanticNames.filter((n) => !densityNames.includes(n));
  files["tokens/tokens.md"] = [
    "Style generated CSS only with these custom properties. Each name is `--lat-` plus the token path with dots as dashes; `{a,b}` lists siblings.",
    "",
    "Semantic (switch with light/dark mode):",
    ...tokenLines(semanticOnly),
    "",
    "Density (switch between default and condensed):",
    ...tokenLines(densityNames),
    "",
    "Fixed:",
    ...tokenLines([...codeOnlyNames, ...elevationNames]),
    "",
  ].join("\n");

  files["README.md"] = [
    "# story-ui-docs (generated)",
    "",
    "Generated by `node packages/cli/bin/latent.mjs story-ui-docs --write` from each component's",
    "`.doc.mjs` and the token JSON. Don't edit these files — the pre-commit hook regenerates them",
    "whenever a `.doc.mjs` or token file changes. Story UI skips README files, so this one costs no",
    "prompt budget.",
    "",
  ].join("\n");

  const considerations = [
    "# Story UI considerations for Latent (generated)",
    "",
    "<!-- Generated by `latent story-ui-docs --write` — don't edit; change packages/cli/bin/story-ui-docs.mjs. -->",
    "",
    "## Component Library Details",
    "",
    "**Library Name**: Latent",
    `**Import Path**: \`${importPath}\``,
    "",
    `Import each component from its own file: \`import { Button } from '${importPath}/Button';\`. Allowed additional imports: none.`,
    "",
    "## Core Principles",
    "",
    "- Compose pages from Latent components; only reach for a plain element when no component fits.",
    "- Every color, spacing, radius, font, and shadow value in CSS is a `var(--lat-*)` custom property from the tokens doc — never a raw hex, px, or rgba literal.",
    "- Set a component's look through its props (`variant`, `size`, and so on), not by overriding its CSS.",
    "- Storybook's toolbar sets light/dark mode and the theme on `<html>`; stories never set `data-latent-mode`, `data-latent-theme`, or `data-latent-density` themselves.",
    "- Fonts are already loaded by the theme; use `var(--lat-font-family-sans)` (or `-mono`/`-serif`), never a font name.",
    "",
    "## Do's and Don'ts",
    "",
    "### ✅ DO",
    "",
    "- Use `var(--lat-spacing-*)` for every gap, padding, and margin in layout CSS.",
    "- Use `var(--lat-color-*)` semantic colors so the story works in both light and dark mode.",
    "- Give icon-only buttons an `aria-label`.",
    "- Follow each component's rules in the catalog docs.",
    "",
    "### ❌ DON'T",
    "",
    "- Don't use `--lat-primitive-*` variables; they skip the semantic layer and won't follow dark mode.",
    "- Don't target a component's internal `.lat-*` class names from a story's CSS module.",
    "- Don't hardcode colors, sizes, or font names.",
    "",
    "## Common Error Patterns",
    "",
    // Story UI only parses items that *start* with **Wrong**: (its regex is
    // /\d+\.\s*\*\*Wrong\*\*:/), so no heading line before it.
    "1. **Wrong**: `color: #6b7280;`",
    "   **Right**: `color: var(--lat-color-text-secondary);`",
    "   **Why**: A hardcoded color ignores the theme and dark mode; the token follows both.",
    "2. **Wrong**: `gap: 24px;`",
    "   **Right**: `gap: var(--lat-spacing-24);`",
    "   **Why**: Spacing tokens shrink in condensed density; literals don't.",
    "3. **Wrong**: `background: var(--lat-primitive-color-gray-50);`",
    "   **Right**: `background: var(--lat-color-surface-sunken);`",
    "   **Why**: Primitives don't change between light and dark mode; semantic tokens do.",
    "",
  ].join("\n");

  // --- budgets, measured the way Story UI measures them ---
  const counted = Object.entries(files).filter(([p]) => !path.basename(p).toLowerCase().startsWith("readme"));
  const overFile = counted.filter(([, c]) => c.length > PER_FILE_BUDGET).map(([p, c]) => ({ path: p, chars: c.length }));
  const total = counted.reduce((n, [, c]) => n + c.length + FILE_HEADER_ALLOWANCE, 0);

  return { files, considerations, budget: { perFile: PER_FILE_BUDGET, total: TOTAL_BUDGET, used: total, overFile } };
}
